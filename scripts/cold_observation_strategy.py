from __future__ import annotations


def cold_observation_section(stage: str) -> list[str]:
    """Return the shared observation block used by plan reports."""
    return [
        "## 冷门、双选、热门穿盘与历史相似盘口观察策略",
        "",
        f"- 适用阶段：{stage}，与正式/模拟/跳过结论并列输出，不替代三色灯。",
        "- 定位：先判断单选能否直接到绿灯；若单选只能黄灯，再评估胜平负双选或让球双选能否把稳定性提升到可复核绿灯。",
        "- 绿灯优先级：单选绿灯最高；双选升绿次之；让球双选升绿只在盘口落点清晰时使用。",
        "- 黄灯升级条件：双选必须覆盖主要风险，同时不能牺牲过多价值分；升级后仍要写清赔率成本和推翻条件。",
        "- 胜平负双选适用：热门不稳、平赔/客胜被压低、战意差或赛制保守时，记录`平/负`或`胜/平`。",
        "- 让球双选适用：热门大概率不崩但穿盘能力不足时，优先记录`让平/让负`；它覆盖一球小胜和不胜两种落点。",
        "- 触发信号：主胜升水、让球退盘、让负被压低、让平低于合理区间、平赔被持续压低。",
        "- 触发信号：小杯赛、附加赛首回合、小组末轮、赛制动机明显不对称、首发轮换未确认。",
        "- 分层：A档可进入21点重点复核；B档只做单场观察；C档噪音直接跳过。",
        "- 升级限制：至少同时满足赔率方向、盘口落点、战意/赛制三个信号，且首发/伤停无重大缺口，才允许黄灯升绿。",
        "- 风控纪律：不能为了凑串升绿；红灯不能通过双选升绿；双选升绿默认不自动进入串关，仍需串关规则单独复核。",
        "- 热门穿盘观察：与冷门双选并列，单独记录`主队 -1 让球胜`或`主队 -2 让球胜`；前10场只进入模拟池，不进入正式方案。",
        "- 穿盘触发：热门胜平负与让球胜至少两个窗口同向强化，亚盘不退盘，大小球支持两球及以上优势，并有至少一项首发/伤停/战意/实力差外部确认。",
        "- 穿盘限制：小联赛、友谊赛、小杯赛或战意不透明场次最多观察绿；盘口退让、赔率反复或多个核心矛盾时跳过。",
        "- 历史相似盘口观察：只使用开赛前快照，滚球盘口与赛前盘口分母严格隔离；亚盘、亚洲大小球、欧赔和竞彩玩法分栏记录。",
        "- 历史匹配门槛：输出样本数、全网/同联赛分栏、亚盘赢走输、亚洲大小球大走小、欧赔胜平负和数据缺口。样本少于20场只记录，不得输出100%概率，不得单独升级执行绿。",
        "",
        "| 字段 | 记录要求 |",
        "|---|---|",
        "| 单选灯色 | 先说明不用双选时是绿/黄/红，避免用双选掩盖低置信 |",
        "| 双选方向 | 写清`平/负`、`胜/平`、`让负`或`让平/让负`，不得只写“防冷” |",
        "| 覆盖价值 | 说明双选覆盖了哪种比分/盘口落点，例如一球小胜、不胜、低比分平局 |",
        "| 赔率成本 | 说明赔率下降或投注覆盖成本，避免把安全感误当价值 |",
        "| 升级判断 | 写清是否从黄灯升绿、只升黄偏绿、或继续观察 |",
        "| 反方证据 | 热门方硬实力、主场、必须赢、首发完整等最大反证 |",
        "| 推翻条件 | 21点赔率回稳、首发强阵、战意确认、盘口重新支撑热门 |",
        "| 执行层级 | 正式/模拟/观察/跳过四选一，默认不因双选自动串关 |",
        "| 热门穿盘观察 | 写清让球胜玩法、赔率变化、亚盘、大小球、外部确认、数据缺口和A/B/C档 |",
        "| 历史相似盘口观察 | 写清赛前样本数、全网/同联赛分栏、亚盘赢走输、亚洲大小球大走小、欧赔胜平负与数据缺口 |",
        "",
        "### 黄灯升级口径",
        "",
        "- 单选已满足价值、稳定、低惩罚时，直接绿灯，不需要双选。",
        "- 单选黄灯但主要风险集中在一个相邻结果时，可用胜平负双选复核升绿。",
        "- 单选黄灯且主要风险集中在穿盘失败时，可用`让平/让负`复核升绿。",
        "- 双选后仍存在两个以上未覆盖的核心风险时，保持黄灯观察。",
        "- 赔率过低或盘口过深导致价值分不足时，即使双选覆盖较好，也最多黄偏绿。",
        "",
    ]


def cold_review_section() -> list[str]:
    """Return the review checklist for observation branches."""
    return [
        "## 冷门、双选、热门穿盘与历史相似盘口观察复盘",
        "",
        "- 单独统计冷门双选、让球双选和黄灯升级样本，不与原始单选方案混算。",
        "- 记录每场赛前单选灯色、双选后灯色、最终执行层级，避免赛后反向美化。",
        "- 记录双选是否覆盖命中，并区分单选命中、胜平负双选覆盖、让球双选覆盖、模拟命中。",
        "- 若黄灯经双选升绿但赛果未覆盖，必须复盘是赔率成本过高、盘口落点误读，还是战意/首发缺口。",
        "- 若黄灯经双选升绿并连续稳定命中，样本少于10场前仍只更新观察日志，不提高主模型权重。",
        "- 若低赔热门击穿正式方案，必须检查是否漏记`让平/让负`或穿盘不足信号。",
        "- 单独统计热门穿盘观察的让球胜命中、失误和走盘；样本少于10场时只记录，不提高主模型权重。",
        "- 单独统计历史相似盘口观察的赛前样本数、全网/同联赛分栏、亚盘赢走输、亚洲大小球大走小、欧赔胜平负、ROI与校准缺口；滚球样本不得混入。",
        "- 历史相似盘口样本门槛未满足时只记录观察，不调整主模型权重。",
        "",
    ]
